#!/usr/bin/env python3
"""Generate the deterministic ISA pressure table used by IronSkies.FlightModel.

Why a table? The simulation must be bit-identical on every platform. `pow`/`exp`
implementations differ in the last ulp between runtimes, so the ISA is sampled once
here and embedded as exact decimal literals. Runtime interpolation is pure arithmetic.

Run from the repository root:

    python3 tools/gen_isa_table.py > src/IronSkies.FlightModel/Atmosphere/IsaTable.g.cs
"""

import math

P0 = 101325.0
T0 = 288.15
G0 = 9.80665
R = 287.05287
L = -0.0065
TROPOPAUSE_M = 11000.0
TOP_M = 20000.0
STEP_M = 100


def pressure(h: float) -> float:
    if h <= TROPOPAUSE_M:
        return P0 * (1.0 + L * h / T0) ** (-G0 / (L * R))
    p11 = P0 * (1.0 + L * TROPOPAUSE_M / T0) ** (-G0 / (L * R))
    return p11 * math.exp(-G0 * (h - TROPOPAUSE_M) / (R * 216.65))


def main() -> None:
    rows = []
    n = int(TOP_M / STEP_M) + 1
    for i in range(n):
        rows.append(pressure(i * STEP_M))

    print("// <auto-generated>")
    print("// Generated by tools/gen_isa_table.py — do not edit by hand.")
    print("// International Standard Atmosphere pressure, 0–20 000 m at 100 m steps.")
    print("// </auto-generated>")
    print("namespace IronSkies.FlightModel.Atmosphere;")
    print()
    print("internal static class IsaTable")
    print("{")
    print(f"    internal const double StepMeters = {STEP_M}.0;")
    print(f"    internal const int Count = {n};")
    print()
    print("    internal static readonly double[] PressurePa =")
    print("    [")
    for i in range(0, n, 4):
        chunk = ", ".join(f"{v:.6f}" for v in rows[i:i + 4])
        print(f"        {chunk},")
    print("    ];")
    print("}")


if __name__ == "__main__":
    main()
