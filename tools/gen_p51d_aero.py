#!/usr/bin/env python3
"""Generate the P-51D-25 Mustang alpha-indexed aero table.

This is an **engineering estimate**, not wind-tunnel data. It is shaped from published
geometry (NACA 45-100 laminar wing, AR 5.83), a finite-wing lift slope, a plausible drag
bucket and a gentle stall break characteristic of the elliptical wing. The numbers are
calibrated so that CLmax gives the documented ~100 mph clean stall at 10,100 lb.

Replace `aero.csv` with measured data when available; the format is the contract.

    python3 tools/gen_p51d_aero.py > game/assets/aircraft/spitfire-mk9/aero.csv
"""

from __future__ import annotations

import sys

# alpha (deg) -> CL, CD, Cm. Piecewise-linear anchors; 1° rows are interpolated below.
CL_ANCHORS = [
    (-10, -0.52), (-6, -0.10), (-2, 0.16), (0, 0.27), (2, 0.43), (4, 0.59),
    (8, 0.90), (10, 1.07), (12, 1.24), (14, 1.38), (15, 1.43), (16, 1.44),
    (17, 1.35), (18, 1.18), (20, 0.92), (22, 0.76), (25, 0.62), (30, 0.50),
]
CD_ANCHORS = [
    (-10, 0.075), (-6, 0.034), (-2, 0.017), (0, 0.0160), (2, 0.0165), (4, 0.0185),
    (8, 0.027), (12, 0.050), (14, 0.072), (16, 0.120), (18, 0.205), (20, 0.300),
    (25, 0.520), (30, 0.680),
]
# Linear static margin: Cm = 0.00 - 0.55·alpha (radians), i.e. stable.
CM_ANCHORS = [
    (-10, 0.105), (-5, 0.052), (0, 0.000), (5, -0.052), (10, -0.105),
    (14, -0.147), (16, -0.168), (18, -0.189), (20, -0.210), (25, -0.262), (30, -0.315),
]


def interp(anchors: list[tuple[float, float]], x: float) -> float:
    if x <= anchors[0][0]:
        return anchors[0][1]
    if x >= anchors[-1][0]:
        return anchors[-1][1]
    for (x0, y0), (x1, y1) in zip(anchors, anchors[1:]):
        if x0 <= x <= x1:
            t = (x - x0) / (x1 - x0)
            return y0 + (y1 - y0) * t
    raise AssertionError("unreachable")


def main() -> None:
    print("# North American P-51D-25 Mustang — estimated aero coefficients.")
    print("# Generated by tools/gen_p51d_aero.py; see validation.md for sources.")
    print("# alpha_deg,cl,cd,cm")
    for alpha in range(-10, 31):
        cl = interp(CL_ANCHORS, alpha)
        cd = interp(CD_ANCHORS, alpha)
        cm = interp(CM_ANCHORS, alpha)
        print(f"{alpha},{cl:.4f},{cd:.5f},{cm:.4f}")


if __name__ == "__main__":
    sys.exit(main())
