#!/usr/bin/env python3
"""Generate the Spitfire LF Mk IX alpha-indexed aero table.

This is an **engineering estimate**, not wind-tunnel data. It is shaped from published
geometry (NACA 2213/2209.4 wing, AR 5.58), a finite-wing lift slope, a plausible drag
bucket and a gentle stall break characteristic of the elliptical wing. The numbers are
calibrated so that CLmax gives the documented ~90 mph clean stall at 7,400 lb.

Replace `aero.csv` with measured data when available; the format is the contract.

    python3 tools/gen_spitfire_aero.py > game/assets/aircraft/spitfire-mk9/aero.csv
"""

from __future__ import annotations

import sys

# alpha (deg) -> CL, CD, Cm. Piecewise-linear anchors; 1° rows are interpolated below.
CL_ANCHORS = [
    (-10, -0.55), (-6, -0.12), (-2, 0.15), (0, 0.28), (2, 0.45), (4, 0.61),
    (8, 0.93), (10, 1.10), (12, 1.27), (14, 1.41), (15, 1.45), (16, 1.46),
    (17, 1.38), (18, 1.22), (20, 0.95), (22, 0.78), (25, 0.64), (30, 0.52),
]
CD_ANCHORS = [
    (-10, 0.080), (-6, 0.038), (-2, 0.022), (0, 0.0215), (2, 0.022), (4, 0.024),
    (8, 0.032), (12, 0.055), (14, 0.078), (16, 0.130), (18, 0.220), (20, 0.320),
    (25, 0.550), (30, 0.700),
]
# Linear static margin: Cm = 0.00 - 0.55·alpha (radians), i.e. stable.
CM_ANCHORS = [
    (-10, 0.096), (-5, 0.048), (0, 0.000), (5, -0.048), (10, -0.096),
    (14, -0.134), (16, -0.154), (18, -0.173), (20, -0.192), (25, -0.240), (30, -0.288),
]


def interp(anchors: list[tuple[float, float]], x: float) -> float:
    if x <= anchors[0][0]:
        return anchors[0][1]
    if x >= anchors[-1][0]:
        return anchors[-1][1]
    for (x0, y0), (x1, y1) in zip(anchors, anchors[1:]):
        if x0 <= x <= x1:
            t = (x - x0) / (x1 - x0)
            return y0 + (y1 - y0) * t
    raise AssertionError("unreachable")


def main() -> None:
    print("# Supermarine Spitfire LF Mk IX — estimated aero coefficients.")
    print("# Generated by tools/gen_spitfire_aero.py; see validation.md for sources.")
    print("# alpha_deg,cl,cd,cm")
    for alpha in range(-10, 31):
        cl = interp(CL_ANCHORS, alpha)
        cd = interp(CD_ANCHORS, alpha)
        cm = interp(CM_ANCHORS, alpha)
        print(f"{alpha},{cl:.4f},{cd:.5f},{cm:.4f}")


if __name__ == "__main__":
    sys.exit(main())
